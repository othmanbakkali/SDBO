/**
 * Apply Language Across DOM
 */
function applyLanguage(lang) {
  if (!SDBO_I18N[lang]) lang = 'fr';
  
  // Store choice
  localStorage.setItem('sdbo_lang', lang);
  
  // Update document attributes
  document.documentElement.lang = lang;
  document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';

  // Update active state of language buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  // Translate elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (SDBO_I18N[lang] && SDBO_I18N[lang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = SDBO_I18N[lang][key];
      } else {
        el.innerHTML = SDBO_I18N[lang][key];
      }
    }
  });

  // Translate placeholders with data-i18n-ph
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (SDBO_I18N[lang] && SDBO_I18N[lang][key]) {
      el.placeholder = SDBO_I18N[lang][key];
    }
  });

  // Translate title/aria attributes with data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (SDBO_I18N[lang] && SDBO_I18N[lang][key]) {
      el.setAttribute('title', SDBO_I18N[lang][key]);
    }
  });
}

// Global initialization
document.addEventListener('DOMContentLoaded', () => {
  const currentLang = localStorage.getItem('sdbo_lang') || 'fr';
  applyLanguage(currentLang);

  // Attach click listeners to language buttons (delegated)
  document.addEventListener('click', (e) => {
    const btn = e.target.closest('.lang-btn');
    if (btn) {
      const chosenLang = btn.getAttribute('data-lang');
      if (chosenLang) {
        applyLanguage(chosenLang);
      }
    }
  });
});
